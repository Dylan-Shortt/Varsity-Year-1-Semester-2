// Method to generate a full report of the student's data
//************************************************//
private String generateFullReport() throws IOException {
    // Logic to generate the full report (placeholder comment)
    return name + "\n\n" + "Mark 1: " + marks[0] + "\n" + "Mark 2: "
            + marks[1] + "\n" + "Mark 3: " + marks[2] + "\n" + "\n" +
            "Highest Mark: " + highestMark + "\n" + "Average Mark: "
            + Math.round(average); // Returns formatted report string
}
