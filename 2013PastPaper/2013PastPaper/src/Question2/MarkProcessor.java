// Method to load student data from a file
//************************************************//
private void loadStudentData() throws IOException {
    BufferedReader reader = new BufferedReader(new FileReader(fileName)); // Create a BufferedReader to read the file
    String line;

    // Clear text fields before loading new data
    jTextField1.setText("");
    jTextField2.setText("");
    jTextField3.setText("");
    jTextField4.setText("");

    // Read data line by line
    while ((line = reader.readLine()) != null) {
        // Process data: read name and marks
        name = line;
        marks[0] = mark1 = reader.readLine();
        marks[1] = mark2 = reader.readLine();
        marks[2] = mark3 = reader.readLine();

        // Display the read data in text fields
        jTextField1.setText(marks[0]);
        jTextField2.setText(marks[1]);
        jTextField3.setText(marks[2]);
        jTextField4.setText(name);
    }

    reader.close(); // Close the reader after loading data
}
