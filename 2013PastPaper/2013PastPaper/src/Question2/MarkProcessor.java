// Method to calculate the average mark
//************************************************//
private String calculateAverageReport() throws IOException {
    BufferedReader reader = new BufferedReader(new FileReader(fileName)); // Create a BufferedReader to read the file
    String line;
    double totalMarks = 0; // Variable to hold total marks
    int studentCount = 3; // Number of students (this should be dynamically tracked in a real scenario)

    // Read marks and calculate total
    while ((line = reader.readLine()) != null) {
        try {
            // Sum marks for three subjects
            totalMarks += Integer.parseInt(reader.readLine()) 
                        + Integer.parseInt(reader.readLine()) 
                        + Integer.parseInt(reader.readLine());
            // Skip the name line
            reader.readLine();
        } catch (NumberFormatException e) {
            // Handle invalid data (e.g., non-numeric values)
            System.err.println("Error parsing integer: " + e.getMessage());
        }
    }

    reader.close(); // Close the reader after processing

    // Check if student count is zero to avoid division by zero
    if (studentCount == 0) {
        return "No valid student data found.\n";
    }

    // Calculate average and return formatted result
    average = totalMarks / studentCount;
    return String.format("Average Mark: %.2f\n", average);
}
//************************************************//

// Method to find the student with the highest mark
//************************************************//
private String findHighestMarkReport() throws IOException {
    BufferedReader reader = new BufferedReader(new FileReader(fileName)); // Create a BufferedReader to read the file
    String line;
    String studentName = ""; // Variable to hold the name of the student with the highest mark

    // Loop to read each student's data
    while ((line = reader.readLine()) != null) {
        String name = line; // Read the student's name
        int mark1 = Integer.parseInt(reader.readLine()); // Read first mark
        int mark2 = Integer.parseInt(reader.readLine()); // Read second mark
        int mark3 = Integer.parseInt(reader.readLine()); // Read third mark

        // Determine the highest mark among the three
        int currentMark = Math.max(mark1, Math.max(mark2, mark3));

        // Update highest mark and corresponding student name if needed
        if (currentMark > highestMark) {
            highestMark = currentMark;
            studentName = name;
        }
    }

    reader.close(); // Close the reader after processing

    // Return the highest mark and the name of the student who achieved it
    return String.format("Highest Mark: %d by %s\n", highestMark, studentName);
}
