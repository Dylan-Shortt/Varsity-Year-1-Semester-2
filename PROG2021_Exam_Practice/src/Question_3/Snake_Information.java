    public static String findSnakeInfo(String snakeName) {
        
        //*************************************************//
        //create a string builder 
        StringBuilder result = new StringBuilder();
        //*************************************************//
        
        //*************************************************//
        //create a try and catch for reading from the file
        try (BufferedReader reader = new BufferedReader(new FileReader("snakes.txt"))) {
            
            //*************************************************//
            //declare var's
            String line;
            boolean found = false;
            int linesAfter = 0;
            //*************************************************//
            
            //*************************************************//
            //create while_ loop to search the text file
            while ((line = reader.readLine()) != null) {
                //*************************************************//
                //checking if_ the snake was found
                if (found) {
                    
                    //*************************************************//
                    //add the snake and the two lines below it to the file
                    result.append(line).append("\n");
                    linesAfter++;
                    //*************************************************//
                    
                    //*************************************************//
                    // Stop after two additional lines
                    if (linesAfter == 2) break;
                    //*************************************************//
                    
                    //*************************************************//
                    //checking for snake 
                } else if (line.trim().equalsIgnoreCase(snakeName)) {
                    //*************************************************//
                    // Add the snake name line
                    result.append(line).append("\n"); 
                    found = true;
                    //*************************************************//
                }
                //*************************************************//
            }
            //*************************************************//
            
            //*************************************************//
            //catch errors
        } catch (IOException e) {
            e.printStackTrace();
        }
        //*************************************************//
        
        //*************************************************//
        //return strinf of snake stuff
        return result.toString();
        //*************************************************//
    }
