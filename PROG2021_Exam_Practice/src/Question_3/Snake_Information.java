    private void populateComboBox() {
    //*************************************************//
    // Create a DefaultComboBoxModel to hold the snake names
    DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>();
    //*************************************************//
    
    //*************************************************//
    // Try-catch block to handle file reading
    try (BufferedReader reader = new BufferedReader(new FileReader("snakes.txt"))) {
        String line;
        
        //*************************************************//
        // Read the file line by line
        while ((line = reader.readLine()) != null) {
            //*************************************************//
            // Check if the line is not empty and doesn't contain ranking/assistance info
            if (!line.trim().isEmpty() && !line.contains("Fatality Ranking") && !line.contains("Medical Assistance")) {
                model.addElement(line.trim()); // Add snake name to the combo box model
            }
            //*************************************************//
            
            //*************************************************//
            // Skip the next two lines after each snake name
            reader.readLine(); // Skip "Fatality Ranking" line
            reader.readLine(); // Skip "Medical Assistance" line
            //*************************************************//
        }
    //*************************************************//
    } catch (IOException e) {
        e.printStackTrace(); // Print any errors during file reading
    }
    //*************************************************//
    
    //*************************************************//
    // Set the model to the combo box to display the snake names
    cmbSnakes.setModel(model);
    //*************************************************//
}

