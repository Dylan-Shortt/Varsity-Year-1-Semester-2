    //method to find the cost of lessons
    private void determineLessonCost()
    {
        //*************************************************//
        //get the cost value from the GUI
        int level = cmbLEVEL.getSelectedIndex();
        int instrument = cmbINSTRUMENT.getSelectedIndex();
        
        int cost = costOfLessons[level][instrument];
        //*************************************************//
        
        //*************************************************//
        //string message to display
        String message = "";
        message = "INSTRUMENT: " + cmbINSTRUMENT.getSelectedItem().toString() + "\n";
        message += "LEVEL: " + cmbLEVEL.getSelectedItem().toString() + "\n";
        message += "LESSON PRICE: R " + cost;
        //*************************************************//
        
        //*************************************************//
        //display lesson cost
        JOptionPane.showMessageDialog(
            null, 
            message, 
            "Music Lessons Price", 
            JOptionPane.INFORMATION_MESSAGE
        );
        //*************************************************//
    }
