    //*************************************************//
    //average cost of lessons
    private void displayAverageLessonCost() 
    {
        
        //*************************************************//
        //string messages for beginner 
        String beginner = "Average lesson price for Beginner: R ";
        String intermediate = "Average lesson price for Intermediate: R ";
        String advanced = "Average lesson price for Advanced: R ";
        //*************************************************//
        
        //*************************************************//
        //create integer values for the averages
        int beginAVG = 0;
        int interAVG = 0;
        int advanAVG = 0;
        
        for (int i = 0; i < costOfLessons.length; i++)
        {
            beginAVG += costOfLessons[0][i];
            interAVG += costOfLessons[1][i];
            advanAVG += costOfLessons[2][i];
        }
        
        beginAVG = beginAVG/costOfLessons.length;
        interAVG = interAVG/costOfLessons.length;
        advanAVG = advanAVG/costOfLessons.length;
        //*************************************************//
        
        //*************************************************//
        //create message 
        String message = "";
        message = beginner + beginAVG + "\n";
        message += intermediate + interAVG + "\n";
        message += advanced + advanAVG + "\n";
        //*************************************************//
        
        //*************************************************//
        //display average lesson cost
        JOptionPane.showMessageDialog(
            null, 
            message, 
            "Message", 
            JOptionPane.INFORMATION_MESSAGE
        );
        //*************************************************//
    }
