    //*************************************************//
    private void SaveDataToATextFile() {
        //*************************************************//
        //get all values before writing to a file
        String message = "MOVIE TICKET REPORT" + "\n";
        message += "*************************************************" + "\n";
        message += ProcessDataToReportScreen() + "\n";
        message += "*************************************************";
        //*************************************************//
        
        //*************************************************//
        try {
            //*************************************************//
            // Create a File object for the text file
            File file = new File("report.txt");
            //*************************************************//
            
            //*************************************************//
            // Pass the File object to the PrintWriter
            PrintWriter writer = new PrintWriter(file);
            //*************************************************//
            
            //*************************************************//
            // Write content to the file
            writer.println(message);
            //*************************************************//
            
            //*************************************************//
            // Close the writer
            writer.close();
            //*************************************************//
            
        } catch (FileNotFoundException e) {
            System.out.println(e);
        }
        //*************************************************//
        
    }
