    //*************************************************//
    //update report Screen
    private String ProcessDataToReportScreen() {
        //*************************************************//
        //create string to return
        String message = "";
        int numberOfTickets = Integer.parseInt(txtNumberOfTickets.getText());
        double ticketPrice = Double.parseDouble(txtTicketPrice.getText());
        //*************************************************//
        
        //*************************************************//
        //populate message
        message += "MOVIE NAME: " + cmbMovieList.getSelectedItem().toString() + "\n";
        message += "MOVIE TICKET PRICE: R " + ticketPrice + "\n";
        message += "NUMBER OF TICKETS: " + numberOfTickets + "\n";
        
        message += "TOTAL TICKET PRICE: R " + tickets.CalculateTotalTicketPrice(numberOfTickets,ticketPrice);
        //*************************************************//
        
        //*************************************************//
        //return string 
        return message;
        //*************************************************//
    }
